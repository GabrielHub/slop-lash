// Hand-written sample champions for the dev gallery, the sim tuner and tests.
// Every sheet is complete and already balanced (validateChampion finds nothing
// and balanceChampion returns it unchanged). Each carries the "input" a player
// might have drawn or typed, so the gallery can ask "would they say that's mine?".

import type { Champion, Move, Narration, Part } from "./sheet";
import type { Delivery, MoveType, PartColor } from "./vocab";

export interface Sample {
  id: string;
  /** What a player might have drawn or typed. */
  input: string;
  champion: Champion;
}

/** `spec` is "role shape size elongation"; `attach` is "parent.anchor" (null for the torso). */
function part(
  id: string,
  spec: string,
  attach: string | null,
  color: PartColor = "primary",
  mirror = false,
): Part {
  const [role, shape, size, elongation] = spec.split(" ") as [
    Part["role"],
    Part["shape"],
    Part["size"],
    Part["elongation"],
  ];
  const [parent, anchor] = attach ? (attach.split(".") as [string, Part["anchor"]]) : [null, null];
  return { id, role, shape, size, elongation, parent, anchor, color, mirror };
}

const move = (name: string, type: MoveType, power: 1 | 2 | 3 | 4 | 5, delivery: Delivery): Move => ({
  name,
  type,
  power,
  delivery,
});

/** A house-voice narration pool; samples override the lines that make them themselves. */
function voice(name: string, custom: Partial<Narration> = {}): Narration {
  return {
    walkOn: custom.walkOn ?? [`${name} enters the arena.`, `Here comes ${name}.`],
    landHit: custom.landHit ?? ["Direct hit!", `${name} connects!`, "That one will leave a mark."],
    takeHit: custom.takeHit ?? [`${name} felt that.`, "Oof. Right in the everything."],
    win: custom.win ?? [`${name} wins it!`, "Victory, somehow."],
    lose: custom.lose ?? [`${name} is down.`, "And that is the end of that."],
    ringOut: custom.ringOut ?? [`${name} has left the building!`, "Over the edge!"],
  };
}

type Draft = Omit<Champion, "narration"> & { narration?: Partial<Narration> };

function sample(id: string, input: string, draft: Draft): Sample {
  return { id, input, champion: { ...draft, narration: voice(draft.name, draft.narration) } };
}

